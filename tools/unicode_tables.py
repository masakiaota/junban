"""Write unicode_tables.h from Python's unicodedata: python3 tools/unicode_tables.py"""
import unicodedata
from pathlib import Path


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, items, comment):
    rows = ",\n".join("    {0x%X, 0x%X}" % r for r in items)
    return "/* %s */\nstatic const struct Unicode_range %s[] = {\n%s\n};\n" % (comment, name, rows)


category = lambda c: unicodedata.category(chr(c))
wide = ranges(lambda c: unicodedata.east_asian_width(chr(c)) in "WF")
zero = ranges(lambda c: c >= 0x300 and category(c) in ("Mn", "Me", "Cf"))
hidden = ranges(lambda c: c >= 0xA0 and (chr(c).isspace() or category(c) in ("Zs", "Zl", "Zp", "Cf")))
text = ("/* Modified for junban in 2026 by junban contributors. */\n"
        "/* Generated by tools/unicode_tables.py from Unicode %s. Do not edit. */\n"
        "struct Unicode_range { unsigned first, last; };\n\n" % unicodedata.unidata_version
        + table("wide_chars", wide, "East Asian Wide and Fullwidth: two terminal columns.") + "\n"
        + table("zero_width_chars", zero, "Combining marks and format characters: no column.") + "\n"
        + table("label_escaped_chars", hidden,
                "Whitespace, line separators and format characters, escaped in labels."))
Path(__file__).resolve().parents[1].joinpath("unicode_tables.h").write_text(text)
